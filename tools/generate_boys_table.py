"""Generate the Boys-function lookup table used by :mod:`hermi.integrals.boys`."""

from __future__ import annotations

import argparse
import math
from pathlib import Path

import numpy as np
import scipy.special


def generate_table(
    resolution: int,
    max_order: int,
    interpolation_order: int,
    max_argument: float,
) -> np.ndarray:
    """Compute Boys values at every point in the interpolation grid."""
    point_count = math.ceil(resolution * max_argument) + 1
    stored_order_count = max_order + interpolation_order
    arguments = np.arange(point_count, dtype=np.float64) / resolution
    orders = np.arange(stored_order_count, dtype=np.float64)
    gamma_orders = orders + 0.5
    safe_arguments = np.where(arguments > 0, arguments, 1.0)

    values = (
        scipy.special.gammainc(gamma_orders, safe_arguments[:, np.newaxis])
        * scipy.special.gamma(gamma_orders)
        / (2 * safe_arguments[:, np.newaxis] ** gamma_orders)
    )
    values[0] = 1 / (2 * orders + 1)
    return values


def source_text(
    table: np.ndarray,
    resolution: int,
    max_order: int,
    interpolation_order: int,
    max_argument: float,
) -> str:
    """Format the generated lookup module."""
    inverse_factorials = [1.0]
    for term in range(1, interpolation_order):
        inverse_factorials.append(inverse_factorials[-1] / term)
    inverse_odd = [1 / (2 * order + 1) for order in range(max_order + 1)]
    flattened = table.ravel()

    def format_values(values: list[float]) -> list[str]:
        return [
            "    " + ", ".join(repr(value) for value in values[start : start + 4]) + ","
            for start in range(0, len(values), 4)
        ]

    lines = [
        '"""Generated by ``tools/generate_boys_table.py``; do not edit."""',
        "",
        "import numpy as np",
        "",
        f"BOYS_RESOLUTION = {resolution}",
        f"BOYS_MAX_ORDER = {max_order}",
        f"BOYS_INTERPOLATION_ORDER = {interpolation_order}",
        f"BOYS_LONG_RANGE_THRESHOLD = {max_argument:.17e}",
        "BOYS_INVERSE_FACTORIALS = np.asarray((",
        *format_values(inverse_factorials),
        "), dtype=np.float64)",
        "BOYS_INVERSE_ODD = np.asarray((",
        *format_values(inverse_odd),
        "), dtype=np.float64)",
        "BOYS_TABLE = np.asarray((",
    ]
    values_per_line = 4
    for start in range(0, flattened.size, values_per_line):
        row = ", ".join(f"{value:.17e}" for value in flattened[start : start + values_per_line])
        lines.append(f"    {row},")
    lines.extend(["), dtype=np.float64).reshape(", f"    {table.shape[0]}, {table.shape[1]}", ")", ""])
    return "\n".join(lines)


def main() -> None:
    """Generate the configured lookup module."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--resolution", type=int, default=8)
    parser.add_argument("--max-order", type=int, default=24)
    parser.add_argument("--interpolation-order", type=int, default=7)
    parser.add_argument("--max-argument", type=float, default=72.0)
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).resolve().parents[1] / "hermi" / "integrals" / "_boys_table.py",
    )
    arguments = parser.parse_args()

    if arguments.resolution <= 0:
        parser.error("--resolution must be positive")
    if arguments.max_order < 0:
        parser.error("--max-order must be nonnegative")
    if arguments.interpolation_order < 1:
        parser.error("--interpolation-order must be positive")
    if not math.isfinite(arguments.max_argument) or arguments.max_argument <= 0:
        parser.error("--max-argument must be finite and positive")

    table = generate_table(
        arguments.resolution,
        arguments.max_order,
        arguments.interpolation_order,
        arguments.max_argument,
    )
    output = arguments.output
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(
        source_text(
            table,
            arguments.resolution,
            arguments.max_order,
            arguments.interpolation_order,
            arguments.max_argument,
        ),
        encoding="utf-8",
    )
    print(output)


if __name__ == "__main__":
    main()
